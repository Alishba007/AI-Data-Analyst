# Deterministic fallback: built only from facts, used if the LLM can't pass
# =============================================================================
def _fallback_summary(facts: dict) -> str:
    out, ov = [], facts.get("overall", {})
    tot_key = next((k for k in ov if k.startswith("total_") and k != "total_profit"
                    and k != "total_quantity"), None)
    s = f"The data has {ov.get('row_count', 0):,} rows"
    if ov.get("distinct_orders"):
        s += f" across {ov['distinct_orders']:,} orders"
    if tot_key:
        s += f", with {tot_key[6:]} totaling {_money(ov[tot_key])}"
    if "total_profit" in ov:
        s += f" and profit of {_money(ov['total_profit'])} ({ov['profit_margin_pct']}% margin)"
    if "date_range" in facts:
        s += f", covering {facts['date_range']['from']} to {facts['date_range']['to']}"
    out.append(s + ".")

    t = facts.get("trend")
    if t:
        s = (f"From {t['first_complete_year']} to {t['last_complete_year']} the total moved from "
             f"{_money(t['first_total'])} to {_money(t['last_total'])} ({t['change_pct']}% change")
        if "cagr_pct" in t:
            s += f", {t['cagr_pct']}% CAGR"
        out.append(s + ").")

    se = facts.get("seasonality")
    if se:
        pk = ", ".join(x["month"] for x in se["peak_months"])
        lo = ", ".join(x["month"] for x in se["lowest_months"])
        out.append(f"The peak months are {pk}, contributing {se['peak_three_months_share_pct']}% "
                   f"of the average year, and the lowest are {lo}.")

    n = 0
    for k, v in facts.items():
        if k.startswith("by_") and k != "by_year" and isinstance(v, dict) and n < 2:
            segs = {x["segment"]: x for x in v["segments"]}
            big, small = segs.get(v["largest"]), segs.get(v["smallest"])
            if big and small:
                out.append(f"By {k[3:]}, {v['largest']} is the largest at {big['share_pct']}% of the total "
                           f"and {v['smallest']} is the smallest at {small['share_pct']}%.")
                n += 1

    worst_loss = None
    for k, v in facts.items():
        if k.startswith("by_") and k != "by_year" and isinstance(v, dict) and "lowest_margin" in v:
            segs = {x["segment"]: x for x in v["segments"]}
            lo, hi = segs.get(v["lowest_margin"]), segs.get(v["highest_margin"])
            if lo and hi:
                out.append(f"By {k[3:]}, {v['highest_margin']} has the highest margin at {hi['margin_pct']}% "
                           f"and {v['lowest_margin']} the lowest at {lo['margin_pct']}%.")
                if lo["margin_pct"] < 0 and worst_loss is None:
                    worst_loss = lo
                break

    c = facts.get("concentration")
    if c:
        top_key = f"top_{c['top_n_small']}_share_pct"
        s = (f"The top {c['top_n_small']} products account for {c[top_key]}% "
             f"of the total, and {c['pareto']['products_needed']} products "
             f"({c['pareto']['products_needed_pct']}%) make up {c['pareto']['threshold_pct']}% of it")
        lm = c.get("loss_making_products")
        if lm:
            s += f"; {lm['count']} products lose money, a combined {_money(abs(lm['total_loss']))}"
        out.append(s + ".")

    de = facts.get("discount_effect")
    if de and "correlation_discount_vs_profit" in de:
        out.append(f"Discount and profit have a correlation of {de['correlation_discount_vs_profit']}.")

    rec = None
    if worst_loss:
        rec = (f"Recommendation: review pricing and discounting for {worst_loss['segment']}, "
               f"which runs at a {worst_loss['margin_pct']}% margin.")
    elif de and de.get("by_discount_band"):
        w = min(de["by_discount_band"], key=lambda b: b["margin_pct"])
        rec = (f"Recommendation: review discounting in the {w['band'].lower()} band, "
               f"where the margin is {w['margin_pct']}%.")
    elif se:
        rec = f"Recommendation: plan stock and staffing ahead of {se['peak_months'][0]['month']}."
    if rec:
        out.append(rec)
    return " ".join(out)


