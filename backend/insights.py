def generate_insights_fast(table: str, engine=None, schema=None) -> InsightsResponse:
    t0 = time.time()
    facts, queries, frames, skipped, profile = build_facts(table, engine, schema)
    t_sql = time.time() - t0

    facts_json = json.dumps(facts, indent=1, default=str)
    base_prompt = PROMPT.format(facts=facts_json)
    llm = get_llm(0.0)

    summary, problems, prompt, llm_error = "", [], base_prompt, None
    for _ in range(MAX_RETRIES + 1):
        try:
            summary = str(llm.invoke(prompt).content).strip()
        except Exception as e:  # LLM down / rate limited / bad key
            llm_error = e
            print(f">>> insights: LLM call failed: {e}")
            break
        problems = verify_summary(summary, facts)
        if not problems:
            break
        prompt = (base_prompt
                  + f"\n\nYour previous draft had these problems: {problems}. "
                    "Rewrite it fixing every one, using only values copied exactly from the facts.")

    verified = bool(summary) and not problems and llm_error is None
    if not verified:
        print(f">>> insights: using deterministic fallback (problems={problems}, error={llm_error})")
        summary = _fallback_summary(facts)

    notes = build_caveats(facts, skipped, profile)
    text_out = summary
    if notes:
        text_out += "\n\nData notes: " + " ".join(notes)
    text_out += ("\n\nVerification: every number and date was checked against the query results."
                 if verified else
                 "\n\nVerification: the AI narrative failed checks, so this summary was "
                 "generated directly from the query results.")

    print(f">>> insights: sql={t_sql:.1f}s total={time.time() - t0:.1f}s "
          f"verified={verified} queries={len(queries)} skipped={skipped}")
    return InsightsResponse(summary=text_out, sql_queries=queries,
                            datasets=[df.to_dict("records") for df in frames if len(df) > 1])