_MONTH_RE = "|".join(MONTHS)
_DATE_RE = re.compile(
    rf"(?:{_MONTH_RE})\s+\d{{1,2}},\s+\d{{4}}"   # January 3, 2014
    rf"|(?:{_MONTH_RE})\s+\d{{4}}"                # November 2017
    r"|\d{4}-\d{2}(?:-\d{2})?"                    # 2017-11 / 2017-11-05
)
_NUM_RE = re.compile(
    r"(?<![\w.])\$?-?(?P<num>\d[\d,]*(?:\.\d+)?)%?(?P<suf>[KkMmBb](?![A-Za-z]))?")
_HEDGE_RE = re.compile(
    r"\b(likely|possibly|probably|appears?|might|may|suggests?|could|perhaps|seems?)\b", re.I)
_HIGH_RE = re.compile(r"\b(largest|biggest|led|leads|leading|dominant)\b", re.I)
_LOW_RE = re.compile(r"\b(smallest|trailed|trails|trailing|lagged|lagging|least)\b", re.I)
_GROW_RE = re.compile(r"\b(grew|grow|grows|growth|increase[ds]?|rose|rise|rising|expanded)\b", re.I)
_FALL_RE = re.compile(r"\b(declin\w*|fell|fall|drop\w*|decreas\w*|shrank|shrink\w*|contract\w*)\b", re.I)
_CLAUSE_END = re.compile(r";|,\s*(?:while|whereas|but|and)\b|\s(?:while|whereas|but)\s", re.I)


def _sentences(s: str) -> list[str]:
    return [x for x in re.split(r"(?<=[.!?])\s+(?=[A-Z$\"“(])", s.strip()) if x]


def _walk(obj, nums: set, strs: set):
    if isinstance(obj, bool) or obj is None:
        return
    if isinstance(obj, (int, float)):
        nums.add(round(abs(float(obj)), 2))
    elif isinstance(obj, str):
        strs.add(obj.lower())
    elif isinstance(obj, dict):
        for v in obj.values():
            _walk(v, nums, strs)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            _walk(v, nums, strs)


def _name_index(facts: dict):
    """name -> set of numbers that belong to it; plus leader/trailer sets."""
    by_name, leaders, trailers = {}, set(), set()

    def collect(o):
        if isinstance(o, dict):
            names = []
            if isinstance(o.get("segment"), str):
                names = [o["segment"]]
            elif isinstance(o.get("product"), str):
                names = [o["product"]]
            elif isinstance(o.get("values"), list):
                names = [str(v) for v in o["values"]]
            if names:
                nums = set()
                _walk({k: v for k, v in o.items() if k not in ("segment", "product", "values")},
                      nums, set())
                for n in names:
                    by_name.setdefault(n, set()).update(nums)
            for v in o.values():
                collect(v)
        elif isinstance(o, (list, tuple)):
            for v in o:
                collect(v)

    collect(facts)
    for k, v in facts.items():
        if k.startswith("by_") and k != "by_year" and isinstance(v, dict):
            leaders.add(v.get("largest"))
            trailers.add(v.get("smallest"))
    return by_name, (leaders - trailers) - {None}, (trailers - leaders) - {None}


def _name_pattern(names):
    names = sorted((n for n in names if n), key=len, reverse=True)
    if not names:
        return None
    return re.compile("|".join(rf"(?<!\w){re.escape(n)}(?!\w)" for n in names))


def verify_numbers_and_dates(summary: str, facts: dict) -> list[str]:
    """Every date and number must exactly equal a value in the facts."""
    nums, strs = set(), set()
    _walk(facts, nums, strs)
    by_name, _, _ = _name_index(facts)
    problems = []

    for m in _DATE_RE.findall(summary):
        if m.lower() not in strs:
            problems.append(f"date '{m}'")
    rest = _DATE_RE.sub(" ", summary)

    # month names used on their own (e.g. "November") must come from the facts
    allowed_months = {m for m in MONTHS if any(m.lower() in s for s in strs)}
    for m in set(re.findall(rf"\b({_MONTH_RE})\b", rest)):
        if m not in allowed_months:
            problems.append(f"month '{m}'")

    pat = _name_pattern(by_name)          # names may contain digits - don't treat those as numbers
    if pat:
        rest = pat.sub(" ", rest)
    for m in _NUM_RE.finditer(rest):
        if m.group("suf"):
            problems.append(f"abbreviated number '{m.group(0).strip()}'")
            continue
        try:
            val = round(abs(float(m.group("num").replace(",", ""))), 2)
        except ValueError:
            continue
        if val not in nums:
            problems.append(f"number '{m.group(0).strip()}'")
    return list(dict.fromkeys(problems))


def verify_structure(summary: str, facts: dict) -> list[str]:
    problems, sents = [], _sentences(summary)
    if not 5 <= len(sents) <= 10:
        problems.append(f"expected 6-9 sentences, got {len(sents)}")
    if not sents or not sents[-1].lower().startswith("recommendation:"):
        problems.append("last sentence must start with 'Recommendation:'")
    for w in sorted(set(x.lower() for x in _HEDGE_RE.findall(summary))):
        problems.append(f"hedging word '{w}'")
    if re.search(r"\b[a-z]+_[a-z_]+\b", summary) or "cited" in summary.lower():
        problems.append("leaked field names or 'cited from'")

    # direction: a positive figure must not be described as a decline, and vice versa
    t = facts.get("trend") or {}
    for key in ("change_pct", "cagr_pct", "latest_yoy_pct"):
        v = t.get(key)
        if v is None or v == 0:
            continue
        cands = {f"{abs(v):.1f}", f"{abs(v):g}"}
        for s in sents:
            if any(re.search(rf"(?<![\d.]){re.escape(c)}(?!\d)", s) for c in cands):
                if v < 0 and _GROW_RE.search(s) and not _FALL_RE.search(s):
                    problems.append(f"{key} is negative but described as growth")
                if v > 0 and _FALL_RE.search(s) and not _GROW_RE.search(s):
                    problems.append(f"{key} is positive but described as a decline")
    return problems


def verify_binding(summary: str, facts: dict) -> list[str]:
    """
    A number written right after a segment/product name must belong to THAT
    name ("West 29.5%" fails if 29.5% is East's share), and size words
    (largest / smallest) must match the facts.
    """
    by_name, leaders_only, trailers_only = _name_index(facts)
    pat = _name_pattern(by_name)
    if not pat:
        return []
    global_ok = set()
    for k in ("overall", "trend", "outliers"):
        _walk(facts.get(k, {}), global_ok, set())
    problems = []
    for sent in _sentences(summary):
        ms = list(pat.finditer(sent))
        for i, m in enumerate(ms):
            end = ms[i + 1].start() if i + 1 < len(ms) else len(sent)
            window = sent[m.end(): min(end, m.end() + 90)]
            cut = _CLAUSE_END.search(window)
            if cut:
                window = window[:cut.start()]
            name = m.group(0)
            for nm in _NUM_RE.finditer(window):
                if nm.group("suf"):
                    continue
                raw = nm.group("num").replace(",", "")
                if re.fullmatch(r"(19|20)\d\d", raw):
                    continue  # a year
                val = round(abs(float(raw)), 2)
                if val not in by_name[name] and val not in global_ok:
                    problems.append(f"'{name}' is followed by {nm.group(0).strip()}, "
                                    f"which is not one of its values")
            if _HIGH_RE.search(window) and name in trailers_only:
                problems.append(f"'{name}' is described as large/leading but is the smallest")
            if _LOW_RE.search(window) and name in leaders_only:
                problems.append(f"'{name}' is described as small/trailing but is the largest")
    return list(dict.fromkeys(problems))


def verify_summary(summary: str, facts: dict) -> list[str]:
    return (verify_numbers_and_dates(summary, facts)
            + verify_structure(summary, facts)
            + verify_binding(summary, facts))


