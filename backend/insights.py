# insights.py
"""
Analyst-grade insights pipeline.

  1. SQL + pandas compute every fact (data quality, metrics, trend/CAGR,
     seasonality, segments with margin/growth/mix shift, concentration,
     outliers, discount drivers). No LLM involved.
  2. ONE LLM call narrates those facts.
  3. The narrative is verified (numbers, dates, structure, label-to-number
     binding, direction/superlative claims). If it fails after retries, a
     deterministic summary built straight from the facts is returned.
  4. Caveats are generated by code, not by the LLM.
"""
import re, json, math, time, traceback
from contextlib import contextmanager
import pandas as pd
from sqlalchemy import text, inspect
from database import get_engine
from agent import get_llm, InsightsResponse

MEASURE_HINTS = ["sales", "revenue", "amount", "total", "price"]
PRIORITY = ["region", "category", "segment", "state", "country", "channel"]
DEPRIORITIZE = ["ship", "id", "postal", "zip"]
MONTHS = ["January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December"]
MAX_RETRIES = 2
TOP_DIMS = 4          # how many categorical columns to analyse
MAX_CARDINALITY = 30  # skip text columns with more distinct values (IDs, free text)
PARETO_PCT = 80
TOP_SMALL, TOP_LARGE = 3, 10
CURRENCY = "$"        # change if your data is not in dollars


# =============================================================================
# Helpers
# =============================================================================
def _q(name: str) -> str:
    """Quote an identifier so capitals/spaces don't break the SQL."""
    return '"' + str(name).replace('"', '""') + '"'


def _py(o):
    """numpy -> python, NaN/inf -> None (keeps the facts JSON valid)."""
    if isinstance(o, dict):
        return {k: _py(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_py(v) for v in o]
    if hasattr(o, "item") and not isinstance(o, (str, bytes)):
        o = o.item()
    if isinstance(o, float) and (math.isnan(o) or math.isinf(o)):
        return None
    return o


def _label_date(s: str) -> str:
    d = pd.to_datetime(s)
    return f"{MONTHS[d.month - 1]} {d.day}, {d.year}"


def _label_month(s: str) -> str:
    d = pd.to_datetime(s + "-01")
    return f"{MONTHS[d.month - 1]} {d.year}"


def _money(v: float) -> str:
    return f"{CURRENCY}{v:,.2f}"


def _rank(c: str) -> int:
    n = c.lower()
    if any(p in n for p in PRIORITY):
        return 0
    if any(d in n for d in DEPRIORITIZE):
        return 2
    return 1


def _profile_columns(engine, table, schema=None):
    cols = inspect(engine).get_columns(table, schema=schema)
    names = [c["name"] for c in cols]
    numeric = [c["name"] for c in cols if str(c["type"]).upper().startswith(
        ("INT", "FLOAT", "NUMERIC", "DOUBLE", "REAL", "BIGINT", "SMALLINT", "DECIMAL"))]
    text_cols = [c["name"] for c in cols if "date" not in c["name"].lower()
                 and str(c["type"]).upper().startswith(("TEXT", "VARCHAR", "CHAR"))]

    date_cands = [n for n in names if "date" in n.lower()]
    date_col = next((n for n in date_cands if "order" in n.lower()),
                    date_cands[0] if date_cands else None)
    measure = next((n for h in MEASURE_HINTS for n in numeric if h in n.lower()),
                   numeric[0] if numeric else None)

    def find(pred, pool):
        return next((n for n in pool if pred(n.lower())), None)

    return {
        "all": names, "date": date_col, "measure": measure, "text": text_cols,
        "profit": find(lambda n: "profit" in n, [n for n in numeric if n != measure]),
        "discount": find(lambda n: "discount" in n, numeric),
        "quantity": find(lambda n: "quantity" in n or n == "qty", numeric),
        "order_id": find(lambda n: "order" in n and "id" in n, text_cols),
    }


# =============================================================================
# Step 1: compute every fact (SQL + pandas, no LLM)
# =============================================================================
def build_facts(table: str, engine=None, schema=None):
    engine = engine or get_engine()
    p = _profile_columns(engine, table, schema)
    date_col, measure = p["date"], p["measure"]
    profit, discount, quantity, order_id = p["profit"], p["discount"], p["quantity"], p["order_id"]
    T = f"{_q(schema)}.{_q(table)}" if schema else _q(table)

    facts, queries, frames, skipped = {}, [], [], []

    def run(q, chart=True):
        queries.append(" ".join(q.split()))
        df = pd.read_sql(text(q), engine)
        if chart:
            frames.append(df.copy())  # copy: later column edits must not leak into charts
        return df

    @contextmanager
    def step(name):
        """One failing analysis must not kill the whole report."""
        try:
            yield
        except Exception:
            print(f">>> insights: step '{name}' failed")
            traceback.print_exc()
            skipped.append(name)

    n_rows = int(run(f"SELECT COUNT(*) AS n FROM {T}", False).iloc[0, 0])
    overall = {"row_count": n_rows}
    dq = {}
    facts["overall"], facts["data_quality"] = overall, dq

    # ---- data quality -------------------------------------------------------
    with step("null check"):
        sel = ", ".join(f"SUM(CASE WHEN {_q(c)} IS NULL THEN 1 ELSE 0 END)::int AS c{i}"
                        for i, c in enumerate(p["all"]))
        r = run(f"SELECT {sel} FROM {T}", False).iloc[0]
        dq["columns_with_nulls"] = [{"column": c, "null_count": int(r[f"c{i}"])}
                                    for i, c in enumerate(p["all"]) if int(r[f"c{i}"]) > 0][:5]
    with step("duplicate check"):
        d = int(run(f"SELECT COUNT(*) AS n FROM (SELECT DISTINCT * FROM {T}) x", False).iloc[0, 0])
        dq["duplicate_rows"] = n_rows - d

    if not measure:
        return _py(facts), queries, frames, skipped, p

    M = _q(measure)
    Pf = _q(profit) if profit else None

    # ---- overall metrics ----------------------------------------------------
    total = None
    with step("overall metrics"):
        parts = [f"SUM({M})::float AS sales", f"COUNT(*) FILTER (WHERE {M} <= 0)::int AS nonpos"]
        if profit:   parts.append(f"SUM({Pf})::float AS profit")
        if quantity: parts.append(f"SUM({_q(quantity)})::float AS qty")
        if discount: parts += [f"AVG({_q(discount)})::float AS avg_disc",
                               f"MAX({_q(discount)})::float AS max_disc"]
        if order_id: parts.append(f"COUNT(DISTINCT {_q(order_id)})::int AS orders")
        t = run(f"SELECT {', '.join(parts)} FROM {T}", False).iloc[0]
        total = round(float(t.sales), 2)
        overall[f"total_{measure}"] = total
        overall["average_per_row"] = round(total / n_rows, 2)
        dq["non_positive_value_rows"] = int(t.nonpos)
        if profit:
            overall["total_profit"] = round(float(t.profit), 2)
            overall["profit_margin_pct"] = round(float(t.profit) / total * 100, 1)
        if quantity:
            overall["total_quantity"] = round(float(t.qty), 2)
        if discount:
            frac = float(t.max_disc) <= 1
            overall["average_discount_pct"] = round(float(t.avg_disc) * (100 if frac else 1), 1)
        if order_id:
            overall["distinct_orders"] = int(t.orders)
            overall["average_order_value"] = round(total / int(t.orders), 2)

    if total is None:
        return _py(facts), queries, frames, skipped, p

    # ---- time: trend, CAGR, seasonality -------------------------------------
    complete, partial, growth_years, ym = [], [], None, None
    if date_col:
        D = _q(date_col)
        with step("date range"):
            d = run(f"""SELECT MIN({D}::date)::text AS a, MAX({D}::date)::text AS b
                        FROM {T}""", False).iloc[0]
            facts["date_range"] = {"from": _label_date(d.a), "to": _label_date(d.b)}

        with step("yearly trend"):
            ym = run(f"""SELECT TO_CHAR({D}::date,'YYYY-MM') AS month,
                                SUM({M})::float AS total
                         FROM {T} WHERE {D} IS NOT NULL GROUP BY 1 ORDER BY 1""")
            ym["year"] = ym.month.str[:4].astype(int)
            ym["moy"] = ym.month.str[5:7].astype(int)
            counts = ym.groupby("year").size()
            complete = sorted(int(y) for y, c in counts.items() if c == 12)
            partial = sorted(int(y) for y, c in counts.items() if c < 12)

            pc = f", SUM({Pf})::float AS profit" if profit else ""
            yr = run(f"""SELECT EXTRACT(YEAR FROM {D}::date)::int AS year,
                                SUM({M})::float AS total{pc}
                         FROM {T} WHERE {D} IS NOT NULL GROUP BY 1 ORDER BY 1""")
            recs = []
            for i, r in enumerate(yr.itertuples()):
                y, prev = int(r.year), (yr.iloc[i - 1] if i else None)
                rec = {"year": y, "total": round(float(r.total), 2),
                       "months_covered": int(counts.get(y, 0))}
                if profit:
                    rec["profit"] = round(float(r.profit), 2)
                    rec["margin_pct"] = round(float(r.profit) / float(r.total) * 100, 1)
                ok = (prev is not None and y in complete and int(prev.year) == y - 1
                      and int(prev.year) in complete and prev.total > 0)
                rec["yoy_pct"] = round((r.total / prev.total - 1) * 100, 1) if ok else None
                recs.append(rec)
            facts["by_year"] = recs
            if partial:
                facts["partial_years"] = partial

            cy = [r for r in recs if r["year"] in complete]
            if len(cy) >= 2 and cy[0]["total"] > 0:
                first, last = cy[0], cy[-1]
                span = last["year"] - first["year"]
                trend = {"first_complete_year": first["year"], "first_total": first["total"],
                         "last_complete_year": last["year"], "last_total": last["total"],
                         "change_pct": round((last["total"] / first["total"] - 1) * 100, 1),
                         "years_spanned": span}
                if span >= 1:
                    trend["cagr_pct"] = round(((last["total"] / first["total"]) ** (1 / span) - 1) * 100, 1)
                if last["yoy_pct"] is not None:
                    trend["latest_yoy_pct"] = last["yoy_pct"]
                if profit:
                    trend["first_year_margin_pct"] = first["margin_pct"]
                    trend["last_year_margin_pct"] = last["margin_pct"]
                facts["trend"] = trend
                growth_years = (first["year"], last["year"])

        with step("seasonality"):
            if ym is not None and complete:
                avg = ym[ym.year.isin(complete)].groupby("moy").total.mean()
                if len(avg) >= 6:
                    order = avg.sort_values(ascending=False)
                    top, low = order.head(3), order.tail(3).iloc[::-1]
                    facts["seasonality"] = {
                        "based_on_complete_years": len(complete),
                        "peak_months": [{"month": MONTHS[int(m) - 1], "average_total": round(float(v), 2)}
                                        for m, v in top.items()],
                        "lowest_months": [{"month": MONTHS[int(m) - 1], "average_total": round(float(v), 2)}
                                          for m, v in low.items()],
                        "peak_three_months_share_pct": round(float(top.sum() / avg.sum() * 100), 1),
                    }

    # ---- segments: share, margin, growth, mix shift -------------------------
    dims = []
    with step("cardinality scan"):
        if p["text"]:
            sel = ", ".join(f"COUNT(DISTINCT {_q(c)})::int AS c{i}" for i, c in enumerate(p["text"]))
            r = run(f"SELECT {sel} FROM {T}", False).iloc[0]
            eligible = [c for i, c in enumerate(p["text"]) if 2 <= int(r[f"c{i}"]) <= MAX_CARDINALITY]
            dims = sorted(eligible, key=_rank)[:TOP_DIMS]

    for col in dims:
        with step(f"segments: {col}"):
            C = _q(col)
            pc = f", SUM({Pf})::float AS profit" if profit else ""
            seg = run(f"SELECT {C} AS segment, SUM({M})::float AS total{pc} "
                      f"FROM {T} GROUP BY 1 ORDER BY 2 DESC")
            seg = seg.dropna(subset=["segment"]).copy()
            seg["segment"] = seg.segment.astype(str)
            seg["share_pct"] = (seg.total / seg.total.sum() * 100).round(1)
            if profit:
                seg["margin_pct"] = (seg.profit / seg.total * 100).round(1)
            if date_col and growth_years:
                sy = run(f"""SELECT {C} AS segment, EXTRACT(YEAR FROM {D}::date)::int AS year,
                                    SUM({M})::float AS total
                             FROM {T} GROUP BY 1, 2""", False)
                sy["segment"] = sy.segment.astype(str)
                piv = sy.pivot_table(index="segment", columns="year", values="total", aggfunc="sum")
                fy, ly = growth_years
                if fy in piv.columns and ly in piv.columns:
                    seg["growth_pct"] = seg.segment.map((piv[ly] / piv[fy] - 1) * 100).round(1)
                    seg["share_shift_pts"] = seg.segment.map(
                        piv[ly] / piv[ly].sum() * 100 - piv[fy] / piv[fy].sum() * 100).round(1)
            keep = [c for c in ["segment", "total", "share_pct", "profit", "margin_pct",
                                "growth_pct", "share_shift_pts"] if c in seg.columns]
            rows = seg if len(seg) <= 8 else pd.concat([seg.head(5), seg.tail(2)])
            entry = {"segment_count": len(seg), "largest": seg.segment.iloc[0],
                     "smallest": seg.segment.iloc[-1],
                     "segments": rows[keep].round(2).to_dict("records")}
            if profit:
                srt = seg.sort_values("margin_pct")
                entry["highest_margin"] = srt.segment.iloc[-1]
                entry["lowest_margin"] = srt.segment.iloc[0]
                entry["loss_making"] = seg[seg.profit < 0].segment.tolist()[:5]
            if growth_years and "growth_pct" in seg.columns:
                g = seg.dropna(subset=["growth_pct"])
                if len(g):
                    entry["fastest_growing"] = g.sort_values("growth_pct").segment.iloc[-1]
                    entry["slowest_growing"] = g.sort_values("growth_pct").segment.iloc[0]
            facts[f"by_{col}"] = entry

    if profit and len(dims) >= 2:
        with step("best/worst combination"):
            a, b = dims[0], dims[1]
            cb = run(f"""SELECT {_q(a)} AS a, {_q(b)} AS b, SUM({M})::float AS total,
                                SUM({Pf})::float AS profit FROM {T} GROUP BY 1, 2""", False)
            cb = cb.dropna(subset=["a", "b"])
            cb = cb[cb.total > 0]

            def pack(r):
                return {"values": [str(r.a), str(r.b)], "total": round(float(r.total), 2),
                        "profit": round(float(r.profit), 2),
                        "margin_pct": round(float(r.profit) / float(r.total) * 100, 1)}
            facts["combinations"] = {"dimensions": f"{a} and {b}",
                                     "worst_by_profit": pack(cb.loc[cb.profit.idxmin()]),
                                     "best_by_profit": pack(cb.loc[cb.profit.idxmax()])}

    # ---- concentration & loss-making products -------------------------------
    prod_col = (next((c for c in p["text"] if "product" in c.lower() and "name" in c.lower()), None)
                or next((c for c in p["text"] if "product" in c.lower() and "id" not in c.lower()), None))
    if prod_col:
        with step("concentration"):
            pc = f", SUM({Pf})::float AS profit" if profit else ""
            pr = run(f"""SELECT {_q(prod_col)} AS product, SUM({M})::float AS total{pc}
                         FROM {T} GROUP BY 1 ORDER BY 2 DESC""", False)
            pr = pr.dropna(subset=["product"]).copy()
            pr["product"] = pr["product"].astype(str)
            frames.append(pr.head(TOP_LARGE).copy())  # chart only the top 10
            ptot = float(pr.total.sum())
            n80 = int((pr.total.cumsum() < ptot * PARETO_PCT / 100).sum() + 1)
            conc = {
                "product_count": len(pr),
                "top_n_small": TOP_SMALL, "top_n_large": TOP_LARGE,
                f"top_{TOP_SMALL}_share_pct": round(float(pr.total.head(TOP_SMALL).sum()) / ptot * 100, 1),
                f"top_{TOP_LARGE}_share_pct": round(float(pr.total.head(TOP_LARGE).sum()) / ptot * 100, 1),
                "pareto": {"threshold_pct": PARETO_PCT, "products_needed": n80,
                           "products_needed_pct": round(n80 / len(pr) * 100, 1)},
                "top_products": pr.head(TOP_SMALL).round(2)[["product", "total"]].to_dict("records"),
            }
            if profit:
                loss = pr[pr.profit < 0]
                conc["loss_making_products"] = {
                    "count": len(loss),
                    "share_of_products_pct": round(len(loss) / len(pr) * 100, 1),
                    "total_loss": round(float(loss.profit.sum()), 2)}
            facts["concentration"] = conc

    # ---- outliers -----------------------------------------------------------
    with step("outliers"):
        o = run(f"""WITH s AS (SELECT AVG({M}) AS a, STDDEV({M}) AS sd FROM {T})
                    SELECT COUNT(*)::int AS n, COALESCE(SUM({M}), 0)::float AS total
                    FROM {T}, s WHERE {M} > s.a + 3 * s.sd""", False).iloc[0]
        facts["outliers"] = {"std_dev_threshold": 3, "rows_above_threshold": int(o.n),
                             "share_of_total_pct": round(float(o.total) / total * 100, 1)}

    # ---- drivers: discount vs profit ---------------------------------------
    if discount and profit:
        with step("discount drivers"):
            Dc = _q(discount)
            r = run(f"SELECT CORR({Dc}::float, {Pf}::float)::float AS r FROM {T}", False).iloc[0, 0]
            eff = {}
            if r is not None and not math.isnan(float(r)):
                eff["correlation_discount_vs_profit"] = round(float(r), 2)
            if overall.get("average_discount_pct") is not None and float(
                    run(f"SELECT MAX({Dc})::float AS m FROM {T}", False).iloc[0, 0]) <= 1:
                bands = run(f"""SELECT CASE WHEN {Dc} = 0 THEN 'No discount'
                                         WHEN {Dc} <= 0.2 THEN 'Low discount'
                                         WHEN {Dc} <= 0.4 THEN 'Medium discount'
                                         ELSE 'High discount' END AS band,
                                       SUM({M})::float AS total, SUM({Pf})::float AS profit,
                                       COUNT(*)::int AS rows, MIN({Dc})::float AS lo
                                FROM {T} GROUP BY 1 ORDER BY 5""")
                bands["margin_pct"] = (bands.profit / bands.total * 100).round(1)
                eff["low_discount_up_to_pct"], eff["medium_discount_up_to_pct"] = 20, 40
                eff["by_discount_band"] = bands[["band", "rows", "total", "profit", "margin_pct"]
                                                ].round(2).to_dict("records")
            if eff:
                facts["discount_effect"] = eff

    return _py(facts), queries, frames, skipped, p


def build_caveats(facts: dict, skipped: list[str], p: dict) -> list[str]:
    """Deterministic caveats - generated by code so they can never be hallucinated."""
    c, ov, dq = [], facts.get("overall", {}), facts.get("data_quality", {})
    for y in facts.get("partial_years", []):
        m = next((r["months_covered"] for r in facts.get("by_year", []) if r["year"] == y), "fewer than 12")
        c.append(f"{y} covers only {m} months, so it is excluded from growth and seasonality figures.")
    if "trend" not in facts and p.get("date"):
        c.append("Fewer than two complete years were available, so trend and CAGR could not be computed.")
    orders = ov.get("distinct_orders")
    if orders and orders < ov["row_count"]:
        c.append(f"Rows are line items, not orders: {ov['row_count']:,} rows belong to {orders:,} distinct orders.")
    if dq.get("duplicate_rows"):
        c.append(f"{dq['duplicate_rows']:,} fully duplicated rows were found and are included in the totals.")
    if dq.get("columns_with_nulls"):
        n = ", ".join(f"{x['column']} ({x['null_count']:,})" for x in dq["columns_with_nulls"])
        c.append(f"Missing values were found in: {n}.")
    if dq.get("non_positive_value_rows"):
        c.append(f"{dq['non_positive_value_rows']:,} rows have a zero or negative value in the main measure.")
    if not p.get("profit"):
        c.append("No profit column was found, so profitability could not be assessed.")
    if "discount_effect" in facts:
        c.append("The discount-profit relationship is a correlation, not proof of cause, "
                 "and no cost data was available.")
    if skipped:
        c.append(f"Some analyses were skipped because of errors: {', '.join(skipped)}.")
    return c


